export interface SchemaRuntimeContext {
  dataCatalogs?: DataCatalogDefinition[];
  classes?: SchoolClass[];
  academicYears?: AcademicYearConfig[];
  rooms?: SchoolRoom[];
  teachers?: Teacher[];
  students?: Student[];
  books?: Book[];
  surveys?: Survey[];
  ruleCategories?: RuleCategory[];
  systemSettings?: SystemSettings;
}

export function buildCatalogLists(context: SchemaRuntimeContext = {}): Record<CatalogKey, string[]> {
  const classNames = Array.from(
    new Set((context.classes || []).map((c) => c.name).filter(Boolean))
  ).sort();

  const yearNames = Array.from(
    new Set(
      [
        context.systemSettings?.academicYear,
        ...(context.academicYears || []).map((y) => y.name),
      ].filter((v): v is string => Boolean(v && v.trim()))
    )
  );

  const roomCodes = Array.from(
    new Set((context.rooms || []).map((r) => r.code || r.name).filter(Boolean))
  ).sort();

  const teacherNames = Array.from(
    new Set((context.teachers || []).map((t) => t.fullName).filter(Boolean))
  ).sort();

  const studentCodes = Array.from(
    new Set((context.students || []).map((s) => s.studentCode).filter(Boolean))
  ).sort();

  const bookCodes = Array.from(
    new Set(
      (context.books || [])
        .map((b) => b.bookCode || b.isbn || b.id)
        .filter(Boolean)
    )
  ).sort();

  const surveyTitles = Array.from(
    new Set((context.surveys || []).map((s) => s.title).filter(Boolean))
  ).sort();

  const ruleCatNames = Array.from(
    new Set((context.ruleCategories || []).map((c) => c.name).filter(Boolean))
  ).sort();

  const teacherSubjects = (context.teachers || []).map((t) => t.subject).filter(Boolean);
  const catalogSubjects = resolveCatalogOptions({
    catalogId: 'teacher_subject',
    runtime: { dataCatalogs: context.dataCatalogs },
  }).map((o) => o.value);
  const subjects = Array.from(
    new Set([...(catalogSubjects.length > 0 ? catalogSubjects : DEFAULT_SUBJECTS), ...teacherSubjects])
  );

  const roles = Object.keys(ROLE_DEFINITIONS);

  return {
    classes: classNames,
    academicYears: yearNames.length > 0 ? yearNames : ['2026 - 2027'],
    rooms: roomCodes,
    teachers: teacherNames,
    students: studentCodes,
    books: bookCodes,
    subjects,
    roles,
    surveys: surveyTitles,
    ruleCategories:
      ruleCatNames.length > 0
        ? ruleCatNames
        : ['Chuyên cần & Giờ giấc', 'Tác phong & Đồng phục', 'Học tập & Nề nếp', 'Thành tích & Đóng góp'],
  };
}

export function sanitizeCsvCell(value: unknown): string {
  const str = value === null || value === undefined ? '' : String(value);
  const normalized = str.replace(/\r?\n/g, ' ');
  // Neutralize Excel/CSV formula injection (=, +, -, @, leading tab/CR)
  const safe = /^[=+\-@\t\r]/.test(normalized) ? `'${normalized}` : normalized;
  if (safe.includes(',') || safe.includes('"') || safe.includes('\n')) {
    return `"${safe.replace(/"/g, '""')}"`;
  }
  return safe;
}

export function getFieldHeaderAliases(field: { header: string; key: string; label: string; aliases?: string[] }): string[] {
  return Array.from(
    new Set([field.header, field.label, field.key, ...(field.aliases || [])].map((s) => s.trim()))
  );
}

